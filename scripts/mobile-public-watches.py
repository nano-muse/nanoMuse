"""Bundle the same offline watch engine for Rhino on Android and JavaScriptCore on iOS."""

import argparse
import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "android/src/shared/public-watches"
OUTPUTS = (
    ROOT / "android/src/android/app/src/main/assets/nanomuse/public-watches.js",
    ROOT / "android/src/ios/NanoMuse/Resources/public-watches.js",
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rules = runpy.run_path(str(ROOT / "nanomuse/server/watch_grammar.py"))
    grammar = {
        name.lower(): rules[f"_{name}"].pattern
        for name in (
            "QUOTED",
            "UNCERTAIN",
            "OWN",
            "REQUEST",
            "RELATED",
            "ONGOING",
            "TOPIC_REQUEST",
            "TOPIC_INTEREST",
        )
    }
    # ES5 lacks lookbehind. The scanner tests the preceding character itself.
    grammar["reference"] = rules["_REFERENCE"].pattern.removeprefix("(?<![A-Za-z0-9_./@-])")
    grammar["broad"] = sorted(rules["_BROAD"])
    parts = [
        "// Generated by scripts/mobile-public-watches.py.",
        "var nmWatchGrammar = " + json.dumps(grammar, ensure_ascii=False, sort_keys=True) + ";",
        *(
            (SOURCES / name).read_text(encoding="utf-8")
            for name in ("vendor/sax.js", "readers.js", "ledger.js")
        ),
    ]
    bundle = ("\n".join(parts).rstrip("\n") + "\n").encode()
    stale = []
    for output in OUTPUTS:
        if args.check:
            if not output.exists() or output.read_bytes() != bundle:
                stale.append(str(output.relative_to(ROOT)))
        else:
            output.write_bytes(bundle)
    if stale:
        print("Regenerate with python scripts/mobile-public-watches.py:", *stale)
    return int(bool(stale))


if __name__ == "__main__":
    raise SystemExit(main())
